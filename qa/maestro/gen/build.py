#!/usr/bin/env python3
"""Write flows/<ID>.yaml and config.yaml from the definitions in gen/flows_*.py."""
import re
import os, sys, yaml
here = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, here)
import flows_a, flows_b, flows_c, flows_d
from flows_a import F
root = os.path.dirname(here); out = os.path.join(root, 'flows')
os.makedirs(out, exist_ok=True)
for f in os.listdir(out):
    if f.endswith('.yaml'): os.remove(os.path.join(out, f))
ORDER = ['00-SETUP',
 'PIN-04','PIN-05','PIN-03','PIN-11','PIN-16','PIN-09','SYNC-06',
 'SYNC-01','SYNC-03','TOR-01','TOR-03','TOOL-01','TOOL-04','BC-05','BC-06','BC-09',
 'SYNC-09','SYNC-10','SYNC-11','RCV-01','RCV-04','RCV-05','RCV-06','RCV-07','RCV-08','RCV-09','PAIR-07',
 'UTXO-01','UTXO-05','UTXO-07','SYNC-04','UTXO-02','UTXO-03','UTXO-04',
 'SEND-01','SEND-02','SEND-04','SEND-05','SEND-06','SEND-07','SEND-08','SEND-09','SEND-10','SEND-11','SEND-13','SEND-16','SEND-17','SEND-18','PSBT-02','PSBT-03','ROB-11',
 'SET-15','SYNC-13','SET-12','SYNC-15','SYNC-14','SYNC-17','SYNC-18','PIN-17','PIN-18','SET-01','SET-05','SET-06',
 'COL-12','COL-12b','COL-09','COL-07','COL-08','PAIR-08',
 'COL-01','COL-02','COL-03','COL-04','COL-05','COL-06','COL-14','COL-15','COL-19','COL-17','COL-24','COL-16','COL-11','RCV-10','COL-18',
 'ROB-07','PIN-10','PIN-06','ZZ-RESTORE']
missing = [k for k in F if k not in ORDER]; extra = [k for k in ORDER if k not in F]
assert not missing and not extra, (missing, extra)
for fid in ORDER:
    d = F[fid]
    head = {'appId': '${APP_ID}', 'name': fid, 'tags': d['tags'],
            'properties': {'plan': f"{fid.replace('COL-12b','COL-12')}: {d['plan']}", 'expect': d['expect'], 'known': d['known']}}
    if not d['known']: del head['properties']['known']
    txt = '# Generated by gen/build.py from gen/flows_*.py - edit there, then re-run build.py\n'
    txt += yaml.safe_dump(head, sort_keys=False, allow_unicode=True, width=200) + '---\n' + d['body']
    # Screenshots are evidence only: the lock screen is FLAG_SECURE (screencap returns null), so a
    # screenshot must never fail a flow.
    # optional: is not honoured for a null screencap, so skip screenshots while the lock screen shows.
    txt = re.sub(r'^(\s*)- takeScreenshot: ([^\s{]+)\s*$',
                 r'\1- runFlow: { when: { notVisible: { id: "lockScreenText" } }, commands: [ { takeScreenshot: { path: \2, optional: true } } ] }',
                 txt, flags=re.M)
    open(os.path.join(out, fid + '.yaml'), 'w').write(txt)
cfg = {'flows': ['flows/*'], 'executionOrder': {'continueOnFailure': True, 'flowsOrder': ORDER}}
open(os.path.join(root, 'config.yaml'), 'w').write('# Maestro workspace config (generated by gen/build.py). run.sh passes it with --config.\n' + yaml.safe_dump(cfg, sort_keys=False))
# sanity: every flow parses as YAML
bad = 0
for fid in ORDER:
    try: list(yaml.safe_load_all(open(os.path.join(out, fid + '.yaml'))))
    except Exception as e: bad += 1; print('YAML ERROR', fid, e)
print(f'wrote {len(ORDER)} flows, {bad} YAML errors')
